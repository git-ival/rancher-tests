// Relative-path components mirroring the qa-infra-automation layout. The
// generated upstream artifacts are written at these paths (under the upstream
// output subdirectory) so they can be copied straight into a qa-infra checkout.
const (
	infraTofuDir            = "tofu"
	infraTofuModule         = "modules"
	infraTofuClusterNodes   = "cluster_nodes"
	infraTfvarsFile         = "terraform.tfvars"
	infraTofuEnvFile        = "tofu.env.example"
	infraAnsibleDir         = "ansible"
	infraAnsibleVarsFile    = "vars.yaml"
	infraRancherSubpath     = "rancher/default-ha"
	infraSecurityGroupField = "aws_security_group"
	infraInstanceTypeField  = "instance_type"
)

// UpstreamArtifactPaths returns the qa-infra-relative paths for the three
// generated upstream files, derived from the provider/distro/env in cfg:
//   - tofu/<provider>/modules/cluster_nodes/terraform.tfvars
//   - ansible/<distro>/<env>/vars.yaml
//   - ansible/rancher/default-ha/vars.yaml
func UpstreamArtifactPaths(cfg envconfig.UpstreamConfig) (tfvars, clusterVars, rancherVars string) {
	tfvars = filepath.Join(infraTofuDir, cfg.Provider, infraTofuModule, infraTofuClusterNodes, infraTfvarsFile)
	clusterVars = filepath.Join(infraAnsibleDir, cfg.KubernetesDistro, cfg.Env, infraAnsibleVarsFile)
	rancherVars = filepath.Join(infraAnsibleDir, infraRancherSubpath, infraAnsibleVarsFile)
	return tfvars, clusterVars, rancherVars
}

// TofuEnvFilePath returns the qa-infra-relative path for the generated
// tofu.env.example file, placed alongside terraform.tfvars in the same
// cluster_nodes module directory: tofu/<provider>/modules/cluster_nodes/tofu.env.example
func TofuEnvFilePath(cfg envconfig.UpstreamConfig) string {
	return filepath.Join(infraTofuDir, cfg.Provider, infraTofuModule, infraTofuClusterNodes, infraTofuEnvFile)
}

// SupportsTfvars reports whether terraform.tfvars generation is supported for
// the upstream provider. Only AWS has a cluster_nodes tofu module today.
func SupportsTfvars(cfg envconfig.UpstreamConfig) bool {
	return strings.EqualFold(cfg.Provider, types.ProviderAWS)
}

// GenerateTerraformTfvars renders the qa-infra-automation terraform.tfvars for
// the upstream cluster's node topology (AWS cluster_nodes module).
//
// Only topology fields (nodes, aws_volume_size, airgap_setup, proxy_setup) are
// emitted as active (uncommented) assignments. The non-topology fields
// (credentials, networking, and the global instance_type) come from
// cfg.TfvarsTemplate and are emitted as *commented-out* documentation/
// placeholders: they are intended to be supplied at `tofu apply` time via
// TF_VAR_<name> environment variables (see GenerateTofuEnvFile), not via this
// file. A `-var-file` assignment always takes precedence over a TF_VAR_
// environment variable, so leaving them commented here lets the environment
// variables take effect; uncomment a line to hardcode that value instead.
//
// The nodes list is grouped by role signature; when a pool carries a resolved
// instance type it is emitted as a per-group instance_type override.
func GenerateTerraformTfvars(up types.UpstreamCluster, cfg envconfig.UpstreamConfig) ([]byte, error) {
	if !SupportsTfvars(cfg) {
		return nil, fmt.Errorf("terraform.tfvars generation is only supported for provider %q (got %q)",
			types.ProviderAWS, cfg.Provider)
	}

	var buf bytes.Buffer
	buf.WriteString("# Generated by agentic-qa plan-environment (upstream Rancher cluster).\n")
	buf.WriteString("# Mirrors qa-infra-automation tofu/aws/modules/cluster_nodes/terraform.tfvars.\n")
	buf.WriteString("#\n")
	buf.WriteString("# Only the cluster topology (nodes, aws_volume_size, airgap_setup,\n")
	buf.WriteString("# proxy_setup) is set below as active values. The commented-out lines\n")
	buf.WriteString("# document every other variable required by the cluster_nodes module;\n")
	buf.WriteString("# supply them at `tofu apply` time via TF_VAR_<name> environment\n")
	buf.WriteString("# variables instead of uncommenting them here (see the generated\n")
	buf.WriteString("# tofu.env.example alongside this file). A -var-file assignment always\n")
	buf.WriteString("# overrides a TF_VAR_ environment variable, so keep these commented\n")
	buf.WriteString("# unless you intend to hardcode a value.\n")
	buf.WriteString("#\n")
	buf.WriteString("# Usage (run from qa-infra-automation repo root):\n")
	buf.WriteString("#   1. cp this file to tofu/aws/modules/cluster_nodes/terraform.tfvars\n")
	buf.WriteString("#   2. set -a; source tofu.env.example (filled in); set +a\n")
	buf.WriteString("#   3. make infra-up\n")
	fmt.Fprintf(&buf, "# Total upstream nodes: %d\n\n", up.TotalNodes)

	// Resolve the global (top-level) instance_type from the upstream node
	// pools' recommended specs. When resolved it is emitted as an active
	// top-level value (the module requires instance_type and uses it as the
	// default for any node group without a per-group override); otherwise it
	// falls back to the commented-out ${VAR} template line below.
	topInstanceType := upstreamInstanceType(up)

	// Non-topology fields, sorted for determinism, commented out. Values come
	// from TF_VAR_<name> environment variables at apply time. aws_security_group
	// is a list. instance_type is emitted active below when resolved, so it is
	// skipped here in that case; per-node instance_type overrides (below, in
	// `nodes`) remain active regardless.
	for _, key := range sortedKeysStr(cfg.TfvarsTemplate) {
		val := cfg.TfvarsTemplate[key]
		if key == infraInstanceTypeField && topInstanceType != "" {
			// Emitted as an active value below.
			continue
		}
		if key == infraSecurityGroupField {
			fmt.Fprintf(&buf, "# %s = [%s]\n", key, hclString(val))
			continue
		}
		fmt.Fprintf(&buf, "# %s = %s\n", key, hclString(val))
	}

	// Top-level instance_type: the resolved global default for node groups
	// without a per-group override. Emitted active when a spec resolved it.
	if topInstanceType != "" {
		fmt.Fprintf(&buf, "\ninstance_type = %s\n", hclString(topInstanceType))
	}

	// Volume size: prefer a resolved spec disk size, else the baseline. This
	// is a topology-derived value, so it is emitted active.
	volume := cfg.BaselineVolumeSizeGiB
	if d := maxPoolDisk(up.NodePools); d > 0 {
		volume = d
	}
	if volume > 0 {
		fmt.Fprintf(&buf, "aws_volume_size = %d\n", volume)
	}

	// nodes = [ { count, role = [...], instance_type? } ]
	buf.WriteString("\nnodes = [\n")
	for _, n := range up.NodePools {
		roles := infraRoles(n)
		fmt.Fprintf(&buf, "  { count = %d, role = [%s]", maxInt(n.Quantity, 1), hclStringList(roles))
		if n.Spec != nil && n.Spec.InstanceType != "" {
			fmt.Fprintf(&buf, ", instance_type = %s", hclString(n.Spec.InstanceType))
		}
		buf.WriteString(" },\n")
	}
	buf.WriteString("]\n")

	// airgap/proxy are required variables in the module; default to false.
	buf.WriteString("\nairgap_setup = false\n")
	buf.WriteString("proxy_setup  = false\n")

	return buf.Bytes(), nil
}

